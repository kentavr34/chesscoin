# -*- coding: utf-8 -*-
"""САМОПРОВЕРКА СТРАЖЕЙ — инструмент обязан доказать, что не врёт.

Кенан 05.08.2026: «если инструмент говорит, что всё плохо, сперва стоит
проверить инструмент». За один день проверки соврали дважды:

  · счётчик непереведённых считал КЛЮЧИ таблиц соответствий, и каждый новый
    стиль фигур «ухудшал» перевод;
  · замер подсветки смотрел на саму клетку, а стили лежат на дочернем
    элементе — я полчаса чинила доску, которая работала.

Оба раза я верила инструменту и шла править продукт. Здесь — образцы с
заранее известным ответом. Если страж на них ошибётся, он скажет об этом
сам, до того как отправит меня чинить исправное.

Запуск:  python project_management/tools/selftest_guards.py
"""
import io
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import i18n_audit  # noqa: E402

# ── Образец: что счётчик непереведённых ОБЯЗАН и НЕ ОБЯЗАН находить ─────────
SAMPLE = """\
import { useText } from '@/i18n/useT';

// Комментарий по-русски считаться не должен.
const TABLE: Record<string, string> = {
  'Golden pieces': 'sepia(1)',
  'Серебряные фигуры': 'grayscale(1)',
};

export const C = () => {
  const label = useText('shop.priceLabel', 'Цена');
  return <div title="Всплывающая подсказка">Жёстко зашитая строка</div>;
};
"""

# Что должно найтись: текст в разметке, атрибут-подсказка. Что нет: ключи
# таблицы (по ним ИЩУТ настройку), запасное значение useText (ключ переведён),
# комментарий.
ДОЛЖНО_НАЙТИСЬ = {'Жёстко зашитая строка', 'Всплывающая подсказка'}
НЕ_ДОЛЖНО = {'Golden pieces', 'Серебряные фигуры', 'Цена', 'shop.priceLabel'}

def проверить_счётчик_переводов():
    tmp = tempfile.mkdtemp()
    path = os.path.join(tmp, 'Sample.tsx')
    io.open(path, 'w', encoding='utf-8').write(SAMPLE)
    found = {body for _, _, body in i18n_audit.scan_file(path, 'Sample.tsx')}

    проблемы = []
    for нужное in ДОЛЖНО_НАЙТИСЬ:
        if not any(нужное in f for f in found):
            проблемы.append('пропустил видимый текст: %s' % нужное)
    for лишнее in НЕ_ДОЛЖНО:
        if any(лишнее in f for f in found):
            проблемы.append('посчитал лишнее: %s' % лишнее)
    return проблемы


ПРОВЕРКИ = [
    ('счётчик непереведённых строк', проверить_счётчик_переводов),
]

if __name__ == '__main__':
    все = []
    for имя, fn in ПРОВЕРКИ:
        проблемы = fn()
        if проблемы:
            все.extend(['%s: %s' % (имя, p) for p in проблемы])
            print('   [X] %s' % имя)
            for p in проблемы:
                print('       %s' % p)
        else:
            print('   [OK] %s' % имя)

    print()
    if все:
        print('GUARDS_SELFTEST_BROKEN=%d' % len(все))
        print('Страж ошибается на образце — верить его выводу нельзя, чинить надо ЕГО.')
        sys.exit(1)
    print('GUARDS_SELFTEST_OK')
