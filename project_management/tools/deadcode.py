REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# Слои и их точки входа. Файл считается живым, если до него есть путь по
# импортам от одной из точек входа своего слоя.
СЛОИ = [
    {
        'имя': 'фронт',
        'корень': 'frontend/src',
        'входы': ['main.tsx', 'App.tsx'],
        'расширения': ('.ts', '.tsx'),
    },
    {
        'имя': 'бэкенд',
        'корень': 'backend/src',
        'входы': ['index.ts', 'server.ts', 'app.ts'],
        'расширения': ('.ts',),
    },
    {
        'имя': 'бот',
        'корень': 'bot/src',
        'входы': ['index.ts', 'bot.ts'],
        'расширения': ('.ts',),
    },
]

# Папки, которые в счёт не идут ни при каких условиях.
ПРОПУСК_ПАПОК = {'node_modules', 'dist', 'build', '.git', '__pycache__',
                 'coverage', '.next', 'chesscoin-archive', 'archive'}


def читать(путь):
    try:
        return io.open(путь, encoding='utf-8', errors='replace').read()
    except OSError:
        return ''


def файлы_слоя(слой):
    корень = os.path.join(REPO, слой['корень'])
    найдено = []
    for база, папки, имена in os.walk(корень):
        папки[:] = [p for p in папки if p not in ПРОПУСК_ПАПОК]
        for имя in имена:
            if имя.endswith(слой['расширения']) and not имя.endswith('.d.ts'):
                путь = os.path.join(база, имя)
                найдено.append(os.path.relpath(путь, корень).replace(os.sep, '/'))
    return sorted(найдено)


def разрешить(источник, цель, корень, все):
    """Импорт → путь файла внутри слоя. Понимает алиас @/ и относительные пути."""
    if цель.startswith('@/'):
        кандидат = цель[2:]
    elif цель.startswith('.'):
        кандидат = os.path.normpath(
            os.path.join(os.path.dirname(источник), цель)).replace(os.sep, '/')
    else:
        return None                      # пакет из node_modules — не наш файл
    for хвост in ('', '.ts', '.tsx', '/index.ts', '/index.tsx'):
        if кандидат + хвост in все:
            return кандидат + хвост
    return None


ИМПОРТ = re.compile(r"""(?:import|export)\s+(?:[\w*{},\s]+\s+from\s+)?['"]([^'"]+)['"]"""
                    r"""|require\(\s*['"]([^'"]+)['"]\s*\)"""
                    r"""|import\(\s*['"]([^'"]+)['"]\s*\)""")

ЭКСПОРТ = re.compile(
    r'^export\s+(?:default\s+)?(?:async\s+)?'
    r'(?:const|let|var|function|class|interface|type|enum)\s+([A-Za-z_$][\w$]*)', re.M)

# const [флаг, setФлаг] = useState(false)
ФЛАГ = re.compile(r'const\s+\[\s*(\w+)\s*,\s*(set\w+)\s*\]\s*=\s*useState(?:<[^>]*>)?\(\s*false\s*\)')


def разобрать_слой(слой):
    корень = os.path.join(REPO, слой['корень'])
    все = файлы_слоя(слой)
    множество = set(все)
    текст = {f: читать(os.path.join(корень, f)) for f in все}

    # ── граф импортов ────────────────────────────────────────────────────────
    рёбра = {f: set() for f in все}
    for f, s in текст.items():
        for m in ИМПОРТ.finditer(s):
            цель = m.group(1) or m.group(2) or m.group(3)
            куда = разрешить(f, цель, корень, множество)
            if куда:
                рёбра[f].add(куда)

    # ── достижимость от точек входа ──────────────────────────────────────────
    входы = [в for в in слой['входы'] if в in множество]
    живые, очередь = set(входы), list(входы)
    while очередь:
        f = очередь.pop()
        for сосед in рёбра.get(f, ()):
            if сосед not in живые:
                живые.add(сосед)
                очередь.append(сосед)
    # Не всё, до чего нет пути по импортам, — балласт. Часть файлов запускает
    # не код, а инструмент снаружи, и импорта там не будет никогда:
    #   · тесты гоняет vitest по маске;
    #   · воркеры подключаются строкой пути (stockfishPool → "stockfishWorker.js").
    # Без этого различия инструмент врал бы на 283 строки живого воркера
    # и на десяток тестов (проверено 05.08.2026).
    весь_текст = '\n'.join(текст.values())
    ПУТЬ_СТРОКОЙ = r"""['"][^'"]*%s\.(?:js|ts|mjs)['"]"""

    def запускается_снаружи(f):
        if '__tests__/' in f or f.endswith(('.test.ts', '.test.tsx', '.spec.ts')):
            return 'тест'
        основа = os.path.basename(f).rsplit('.', 1)[0]
        # имя файла упомянуто строкой — путь воркера, динамический require
        if re.search(ПУТЬ_СТРОКОЙ % re.escape(основа), весь_текст):
            return 'запускается по имени'
        return None

    сироты, снаружи = [], []
    for f in sorted(множество - живые):
        причина = запускается_снаружи(f)
        (снаружи if причина else сироты).append((f, причина) if причина else f)

    # ── экспорт, который никто не ввозит ─────────────────────────────────────
    ввозится = {}          # файл → набор имён, которые из него импортируют
    ИМЕНА = re.compile(r"import\s+(?:type\s+)?\{([^}]*)\}\s+from\s+['\"]([^'\"]+)['\"]")
    for f, s in текст.items():
        for m in ИМЕНА.finditer(s):
            куда = разрешить(f, m.group(2), корень, множество)
            if not куда:
                continue
            для = ввозится.setdefault(куда, set())
            for имя in m.group(1).split(','):
                имя = имя.strip().split(' as ')[0].strip()
                if имя:
                    для.add(имя)

    мёртвый_экспорт = []
    for f in живые:                     # у сирот и так весь файл под вопросом
        s = текст[f]
        нужны = ввозится.get(f, set())
        for имя in set(ЭКСПОРТ.findall(s)):
            if имя in нужны:
                continue
            # своё же имя внутри файла не считаем использованием вовне
            if f in слой['входы']:
                continue
            мёртвый_экспорт.append((f, имя))

    # ── флаги, которые никогда не включаются ─────────────────────────────────
    #
    # Считаем ВСЕ вызовы сеттера и смотрим на аргумент. Флаг мёртв, только если
    # его либо не зовут вовсе, либо зовут исключительно с `false`.
    #
    # Первая версия искала `set(true` и `set(!` — и объявила мёртвыми шесть
    # живых флагов из восьми: переключатель пишется `set(v => !v)`, а значение
    # из данных — `set(ответ.isCommander)`. Проверять надо аргумент, а не
    # начало строки (найдено 09.08.2026 сверкой каждого случая руками).
    выключенные = []
    for f, s in текст.items():
        for имя, сеттер in ФЛАГ.findall(s):
            вызовы = re.findall(re.escape(сеттер) + r'\s*\(\s*([^)]*)', s)
            живые = [а.strip() for а in вызовы if а.strip() and а.strip() != 'false']
            if not живые:
                выключенные.append((f, имя, сеттер))

    строк = {f: текст[f].count('\n') + 1 for f in все}
    return {
        'имя': слой['имя'],
        'корень': слой['корень'],
        'файлов': len(все),
        'строк': sum(строк.values()),
        'входы': входы,
        'сироты': [(f, строк[f]) for f in сироты],
        'снаружи': [(f, строк[f], причина) for f, причина in снаружи],
        'мёртвый_экспорт': sorted(мёртвый_экспорт),
        'выключенные': sorted(выключенные),
    }


# Файлы, которые точно живые: они открыты на экране каждый день. Если разбор
# импортов сломается, они окажутся «сиротами» — и это сразу видно.
ОБРАЗЦЫ_ЖИВЫХ = {
    'фронт': ['pages/ExchangeTab.tsx', 'pages/ShopPage.tsx',
              'components/game/ChessBoard.tsx', 'pages/LessonLearnPage.tsx'],
    'бэкенд': ['routes/tasks.ts', 'services/crons.ts', 'services/prizes.ts'],
}


def самопроверка(отчёты):
    беда = []
    for о in отчёты:
        мёртвые = {f for f, _ in о['сироты']}
        for образец in ОБРАЗЦЫ_ЖИВЫХ.get(о['имя'], []):
            if образец in мёртвые:
                беда.append('%s: живой %s объявлен сиротой' % (о['имя'], образец))
    return беда


