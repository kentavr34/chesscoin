def главное(аргументы):
    полностью = '--full' in аргументы
    как_json = '--json' in аргументы
    # Режим стража: --max N — балласт не должен расти. Печатает одну строку.
    потолок = None
    for i, а in enumerate(аргументы):
        if а == '--max' and i + 1 < len(аргументы):
            потолок = int(аргументы[i + 1])

    отчёты = [разобрать_слой(с) for с in СЛОИ
              if os.path.isdir(os.path.join(REPO, с['корень']))]

    if потолок is not None:
        беда = самопроверка(отчёты)
        if беда:
            print('DEADCODE_TOOL_BROKEN ' + '; '.join(беда))
            return 1
        строк = sum(n for о in отчёты for _, n in о['сироты'])
        if строк > потолок:
            print('DEADCODE_GREW %d>%d' % (строк, потолок))
            return 1
        print('DEADCODE_OK %d<=%d' % (строк, потолок))
        return 0

    if как_json:
        print(json.dumps(отчёты, ensure_ascii=False, indent=1))
        return 0

    print('=' * 74)
    print('КАРТА ФАЙЛОВ И ФУНКЦИЙ'.center(74))
    print('=' * 74)

    всего_сирот = 0
    for о in отчёты:
        сирот_строк = sum(n for _, n in о['сироты'])
        всего_сирот += сирот_строк
        print('\n── %s (%s) ──' % (о['имя'].upper(), о['корень']))
        if not о['входы']:
            print('   ⚠️ точка входа не найдена — достижимость не считалась')
        print('   файлов: %-5d строк: %-7d' % (о['файлов'], о['строк']))
        print('   файлов-сирот: %-4d в них строк: %-6d (%.1f%% слоя)'
              % (len(о['сироты']), сирот_строк,
                 100.0 * сирот_строк / max(1, о['строк'])))
        print('   запускается снаружи: %-4d (тесты, воркеры — не балласт)'
              % len(о['снаружи']))
        print('   мёртвый экспорт: %-4d' % len(о['мёртвый_экспорт']))
        print('   выключенных веток: %-4d' % len(о['выключенные']))

        по_весу = sorted(о['сироты'], key=lambda x: -x[1])
        показать = по_весу if полностью else по_весу[:8]
        for f, n in показать:
            print('      сирота  %-52s %5d стр.' % (f[:52], n))
        if not полностью and len(о['сироты']) > 8:
            print('      … ещё %d — запусти с --full' % (len(о['сироты']) - 8))

        for f, имя, сеттер in (о['выключенные'] if полностью else о['выключенные'][:6]):
            print('      ветка   %-40s флаг %s (%s не включает)' % (f[:40], имя, сеттер))
        if not полностью and len(о['выключенные']) > 6:
            print('      … ещё %d — запусти с --full' % (len(о['выключенные']) - 6))

    беда = самопроверка(отчёты)
    print('\n' + '-' * 74)
    if беда:
        print('🚨 ИНСТРУМЕНТ СЛОМАН — отчёту верить нельзя:')
        for б in беда:
            print('   · %s' % б)
    else:
        print('самопроверка пройдена: живые образцы в сироты не попали')
    print('строк в файлах, до которых нельзя дойти от точки входа: %d' % всего_сирот)
    print("""
Как читать. «Сирота» — файл, до которого нет пути по импортам: скорее всего
балласт, но сначала проверь, не тянет ли его сборщик по имени (страницы,
воркеры, скрипты). «Мёртвый экспорт» — имя объявлено на вывоз, но никто его
не ввозит; часто это остаток от переезда. «Выключенная ветка» — флаг заведён
со значением «нет», и включить его нечем: ровно так 315 строк панели
TON-кошелька дожили до 05.08.2026, скрывая единственную рабочую отвязку.

Инструмент НИЧЕГО НЕ УДАЛЯЕТ и не может: удаление — только с подтверждением.
""")
    return 0


if __name__ == '__main__':
    sys.exit(главное(sys.argv[1:]))
