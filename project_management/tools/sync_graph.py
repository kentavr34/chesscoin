# -*- coding: utf-8 -*-
"""СИНХРОНИЗАЦИЯ ЗНАНИЙ — чтобы граф не отставал от разговоров.

Кенан 09.08.2026: «проверь историю чата — записи в ЦНС, в локальных файлах
истории проекта, в РАГ-памяти и в графах связей; если не дописывались
последние чаты — создай синхронизацию обновлений данных в графах при каждой
сессии».

Проверка это и показала: в ЦНС записи свежие, а выгрузка решений обрывалась
на 04.08 и граф был собран 05.08 — четыре дня разговоров до карты не дошли.
Граф читает файлы, а решения живут в базе; без выгрузки карта показывает
устройство кода, но не замысел.

Что делает:
  1. выгружает свежие решения из ЦНС в docs/history/DECISIONS.md;
  2. пересобирает граф по коду (`graphify update .` — без модели, бесплатно);
  3. говорит, что изменилось, и молчит, если всё уже было свежим.

Смысловой разбор документов (`graphify . --update`) стоит токенов и здесь
НЕ запускается — он нужен, только когда менялись сами документы, и его
запускает человек.

Запуск:
    python project_management/tools/sync_graph.py           # обычный ход
    python project_management/tools/sync_graph.py --quiet   # для хука
    python project_management/tools/sync_graph.py --check   # только проверить
"""
import io
import json
import os
import subprocess
import sys

try:
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
except (AttributeError, OSError):
    pass

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
РЕШЕНИЯ = os.path.join(REPO, 'docs', 'history', 'DECISIONS.md')
ГРАФ = os.path.join(REPO, 'graphify-out', 'graph.json')
ИНСТРУМЕНТЫ = os.path.dirname(os.path.abspath(__file__))


def запустить(команда, таймаут=900):
    """Выполнить и вернуть (код, вывод). Молча переживает отсутствие программы."""
    try:
        r = subprocess.run(команда, cwd=REPO, capture_output=True,
                           encoding='utf-8', errors='replace', timeout=таймаут)
        return r.returncode, (r.stdout or '') + (r.stderr or '')
    except FileNotFoundError:
        return 127, 'программа не найдена: %s' % команда[0]
    except subprocess.TimeoutExpired:
        return 124, 'не уложилось в %d с' % таймаут


def последнее_решение():
    """Дата самой свежей записи в выгрузке решений."""
    if not os.path.exists(РЕШЕНИЯ):
        return None
    for строка in io.open(РЕШЕНИЯ, encoding='utf-8', errors='replace'):
        if строка.startswith('## '):
            return строка[3:].strip()
    return None


def возраст_графа():
    """Сколько узлов и связей и когда собран."""
    if not os.path.exists(ГРАФ):
        return None
    import datetime
    когда = datetime.date.fromtimestamp(os.path.getmtime(ГРАФ)).isoformat()
    try:
        g = json.load(io.open(ГРАФ, encoding='utf-8'))
        return когда, len(g.get('nodes', [])), len(g.get('links', []))
    except (ValueError, OSError):
        return когда, 0, 0


РАГ = 'http://45.67.216.36:9621'
РАГ_КЛЮЧ = 'chesscoin_rag_secret_2026'


def состояние_рага():
    """Третье хранилище — семантическая память ЦНС. Отвечает ли и что в очереди.

    Проверено 09.08.2026. Сервис жив: разбор идёт через DeepSeek, векторизация
    через DashScope, 474 документа уже обработано. Но перед нашими бумагами
    стоит очередь из 475 чужих (задание dh-hermes на 1318 файлов), и документ,
    отправленный сейчас, проиндексируется не сразу.

    Отдельно: ответ «Text successfully received» НЕ значит «сохранено» — он
    значит «положено в очередь». Пока документ не перешёл в processed,
    спрашивать о нём РАГ бесполезно, ответ будет «нет контекста».
    """
    import urllib.request

    def взять(путь, таймаут=40):
        req = urllib.request.Request(РАГ + путь, headers={'X-Api-Key': РАГ_КЛЮЧ})
        with urllib.request.urlopen(req, timeout=таймаут) as r:
            return json.load(r)

    try:
        взять('/health', 15)
    except Exception as e:
        return 'не отвечает (%s)' % str(e)[:60]
    try:
        статусы = взять('/documents').get('statuses', {})
    except Exception:
        return 'отвечает, состав очереди неизвестен'
    сколько = {k: len(v) for k, v in статусы.items()}
    ждут = сколько.get('pending', 0)
    готово = сколько.get('processed', 0)
    упало = сколько.get('failed', 0)
    if готово == 0 and ждут:
        return 'НЕ ИНДЕКСИРУЕТ: %d в очереди, обработано 0 — проверь ключ векторизации' % ждут
    хвост = ', упало %d' % упало if упало else ''
    if ждут:
        return 'обработано %d, ждут очереди %d%s' % (готово, ждут, хвост)
    return 'в порядке: обработано %d%s' % (готово, хвост)


def главное(аргументы):
    тихо = '--quiet' in аргументы
    только_проверить = '--check' in аргументы

    было_решение = последнее_решение()
    было_граф = возраст_графа()

    if not тихо:
        print('=' * 74)
        print('СИНХРОНИЗАЦИЯ ЗНАНИЙ')
        print('=' * 74)
        print('   решения выгружены до: %s' % (было_решение or 'файла нет'))
        if было_граф:
            print('   граф собран %s: %d узлов, %d связей'
                  % (было_граф[0], было_граф[1], было_граф[2]))
        else:
            print('   графа нет — соберётся заново')

    if только_проверить:
        return 0

    # ── 1. Свежие решения из ЦНС ─────────────────────────────────────────────
    код, вывод = запустить([sys.executable,
                            os.path.join(ИНСТРУМЕНТЫ, 'export_history.py')], 300)
    стало_решение = последнее_решение()
    решения_ок = код == 0
    if not тихо:
        if not решения_ок:
            print('\n   ⚠️ выгрузка решений не удалась: %s' % вывод.strip()[:160])
        elif стало_решение != было_решение:
            print('\n   ✅ решения дописаны: %s → %s' % (было_решение, стало_решение))
        else:
            print('\n   решения уже были свежими (%s)' % стало_решение)

    # ── 2. Граф по коду ──────────────────────────────────────────────────────
    код2, вывод2 = запустить(['graphify', 'update', '.'], 900)
    стало_граф = возраст_графа()
    граф_ок = код2 == 0
    if not тихо:
        if not граф_ок:
            print('   ⚠️ граф не пересобрался: %s' % вывод2.strip()[-200:])
        elif стало_граф and было_граф and стало_граф[1:] != было_граф[1:]:
            print('   ✅ граф обновлён: %d → %d узлов, %d → %d связей'
                  % (было_граф[1], стало_граф[1], было_граф[2], стало_граф[2]))
        else:
            print('   граф не изменился — код тот же')

    # ── 3. Семантическая память ЦНС ──────────────────────────────────────────
    рагом = состояние_рага()
    if not тихо:
        print('   РАГ ЦНС: %s' % рагом)

    # Для хука — одна строка, чтобы не засорять начало сессии.
    if тихо:
        части = []
        if решения_ок and стало_решение != было_решение:
            части.append('решения до %s' % стало_решение)
        if граф_ок and стало_граф and было_граф and стало_граф[1:] != было_граф[1:]:
            части.append('граф %d узлов' % стало_граф[1])
        if not решения_ок or not граф_ок:
            части.append('⚠️ часть источников не обновилась')
        if 'НЕ ИНДЕКСИРУЕТ' in рагом:
            части.append('РАГ мёртв (ключ векторизации)')
        if части:
            print('[память] ' + ', '.join(части))

    return 0 if (решения_ок and граф_ок) else 1


if __name__ == '__main__':
    sys.exit(главное(sys.argv[1:]))
