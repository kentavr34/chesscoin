-- Код товара вместо человеческого названия (Кенан 05.08.2026).
--
-- Настройки косметики искались ПО НАЗВАНИЮ: в базе «Silver pieces», в коде
-- «Silver Pieces» — и купленный стиль тихо не применялся. Так не работали
-- девять стилей фигур из десяти и одна рамка: их продавали, за них платили,
-- на экране не менялось ничего.
--
-- Название — текст для людей: его переводят, правят, дополняют. Связывать по
-- нему логику нельзя. Код неизменен и не переводится.
ALTER TABLE items ADD COLUMN IF NOT EXISTS code text;

-- Код собирается из названия один раз: нижний регистр, только буквы и цифры,
-- пробелы и знаки — в подчёркивание.
UPDATE items
SET code = regexp_replace(lower(btrim(name)), '[^a-z0-9]+', '_', 'g')
WHERE code IS NULL OR code = '';
UPDATE items SET code = trim('_' from code);

-- Одинаковые названия у разных типов допустимы («Classic» — и доска, и тема),
-- поэтому уникальность по паре тип+код, а не по коду.
CREATE UNIQUE INDEX IF NOT EXISTS items_type_code_key ON items (type, code);
