/**
 * Распределение призовых касс — турниры и войны.
 *
 * Правила заданы Кенаном 31.07.2026 после разбора: за 10 завершённых турниров
 * собрали 158 000 взносов, выплатили 58 000 — 100 000 монет исчезли. Чемпион
 * недели получал 10% кассы: заплатил 1000, забрал 100. Старые проценты
 * (WORLD 70/20/10, SEASONAL 30, MONTHLY 20, WEEKLY 10) отменены.
 */

// ── ТУРНИРЫ ──────────────────────────────────────────────────────────────────
//
// Касса = взносы + донаты (донат постороннего человека тоже идёт в кассу).
// Делится на три части: 60% / 30% / 10% — первое, второе, третье место,
// НЕЗАВИСИМО от типа турнира. Из каждой доли 10% — комиссия стола, игроку
// уходит 90% его доли.
//
// Пример Кенана: касса 100 000 →
//   1 место 60 000 − 6 000 = 54 000
//   2 место 30 000 − 3 000 = 27 000
//   3 место 10 000 − 1 000 =  9 000
//   комиссия стола          = 10 000
//
// Мест меньше трёх — доли перенормируются между теми, кто есть. Один игрок
// забирает всю кассу минус комиссию (прямое условие Кенана).

const PLACE_WEIGHTS = [60n, 30n, 10n];
export const COMMISSION_PERCENT = 10n;

export interface PotSplit {
  /** Сколько уйдёт игрокам, по местам (индекс 0 = первое место) */
  payouts: bigint[];
  /** Комиссия стола — ровно 10% кассы */
  commission: bigint;
}

/**
 * Разделить кассу турнира между призёрами.
 * @param pot    вся касса: взносы + донаты
 * @param places сколько призёров реально есть (0 — никого)
 *
 * Гарантия: sum(payouts) + commission === pot. Ни одна монета не пропадает —
 * именно на этом сгорели 100 000 в старой схеме.
 */
export function splitTournamentPot(pot: bigint, places: number): PotSplit {
  if (pot <= 0n) return { payouts: [], commission: 0n };
  if (places <= 0) return { payouts: [], commission: pot }; // некому платить

  const weights = PLACE_WEIGHTS.slice(0, Math.min(places, PLACE_WEIGHTS.length));
  const totalWeight = weights.reduce((s, w) => s + w, 0n);

  const gross = weights.map(w => (pot * w) / totalWeight);
  // Остаток от целочисленного деления — первому месту, чтобы сумма сошлась.
  gross[0] += pot - gross.reduce((s, g) => s + g, 0n);

  const payouts = gross.map(g => g - (g * COMMISSION_PERCENT) / 100n);
  const commission = pot - payouts.reduce((s, p) => s + p, 0n);

  return { payouts, commission };
}

// ── ВОЙНЫ ────────────────────────────────────────────────────────────────────
//
// Правило Кенана 31.07.2026, заменяет прежнее распределение.
//
// У каждой страны своя казна: взносы вступающих воинов + донаты. Две страны
// объявляют войну. Победившая по числу побед забирает казну проигравшей
// ДО НУЛЯ — своя казна остаётся при ней. Захваченное делится между своими
// воинами строго по числу побед, которые они принесли команде.
//
// Считаем эквивалентами: одна победа = один эквивалент. Доля воина =
// захваченная касса × его победы ÷ сумма побед всех. Кто внёс деньги, но не
// сыграл ни одной партии, не получает ничего — прямое условие Кенана.

export interface WarShare {
  userId: string;
  wins: number;
  amount: bigint;
}

/**
 * Разделить захваченную казну между воинами-победителями кратно их победам.
 * @param pot     казна проигравшей страны, забирается целиком
 * @param winners воины страны-победителя с числом побед в этой войне
 *
 * Гарантия: sum(amount) === pot, если хоть кто-то победил. Остаток от деления
 * достаётся тому, кто принёс больше побед.
 */
export function splitWarPot(
  pot: bigint,
  winners: Array<{ userId: string; wins: number }>,
): WarShare[] {
  if (pot <= 0n) return [];

  const scoring = winners
    .filter(w => w.wins > 0)
    .sort((a, b) => b.wins - a.wins);
  if (scoring.length === 0) return []; // никто не победил — делить не по чему

  const totalWins = BigInt(scoring.reduce((s, w) => s + w.wins, 0));
  const shares = scoring.map(w => ({
    userId: w.userId,
    wins: w.wins,
    amount: (pot * BigInt(w.wins)) / totalWins,
  }));

  // Остаток — лучшему по победам, чтобы касса разошлась до последней монеты.
  shares[0].amount += pot - shares.reduce((s, x) => s + x.amount, 0n);

  return shares;
}
